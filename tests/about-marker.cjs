const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const marker = fs.readFileSync(path.join(root, 'patches/patch-source/about-marker.js'), 'utf8');
const filter = fs.readFileSync(path.join(root, 'patches/patch-source/response-filter.js'), 'utf8');
let documentAccess = 0;
let callback;
let timers = 0;
const text = {nodeType: 3, nodeValue: '5.30.320/web_fixture', parentNode: {style: {}}};
const body = {nodeType: 1, textContent: 'App version Device Client', childNodes: [text]};
const context = vm.createContext({setInterval(fn) {callback = fn; timers++;}});
Object.defineProperty(context, 'document', {configurable: true, get() {documentAccess++; throw Error('Native DOM not ready');}});
vm.runInContext(filter + marker, context);
assert.equal(documentAccess, 0, 'no native DOM access during early injection');
Object.defineProperty(context, 'document', {value: {body}, configurable: true});
vm.runInContext('JSON.parse(\'{"responseContext":{}}\')', context);
assert.equal(timers, 1);
assert.equal(text.nodeValue, '5.30.320/web_fixture\npearlxcore was here');
callback();
assert.equal(text.nodeValue.split('pearlxcore was here').length - 1, 1);
vm.runInContext(filter + marker, context);
vm.runInContext('JSON.parse(\'{"responseContext":{}}\')', context);
assert.equal(timers, 1, 'no duplicate timer on repeated injection');
text.nodeValue = '5.30.320/web_secondvisit';
callback();
assert.equal(text.nodeValue, '5.30.320/web_secondvisit\npearlxcore was here');
body.textContent = 'Unrelated settings';
text.nodeValue = '5.30.320/web_other';
callback();
assert.equal(text.nodeValue, '5.30.320/web_other', 'About-only gating');
console.log('PASS deferred bootstrap, idempotency, About revisit and page gating');
